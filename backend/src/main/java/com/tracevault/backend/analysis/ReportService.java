package com.tracevault.backend.analysis;

import org.springframework.stereotype.Service;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Membuat laporan teks yang bisa diunduh.
 * Bentuk jawabannya { content, filename, format } sama dengan yang dibaca frontend/js/results.js.
 * (Ekspor PDF sungguhan bisa ditambahkan nanti dengan library seperti OpenPDF.)
 */
@Service
public class ReportService {

    public record ReportResponse(String content, String filename, String format) {}

    public ReportResponse build(AnalysisResponse a) {
        String line = "─".repeat(60);
        List<String> out = new ArrayList<>(List.of(
                "TRACEVAULT FORENSIC ANALYSIS REPORT",
                line,
                "Analysis ID   : " + a.id(),
                "File          : " + a.name(),
                "Analysis Type : " + a.type(),
                "Date          : " + a.createdAt(),
                "Risk Score    : " + a.riskScore() + "/100 (" + a.riskLevel().toUpperCase(Locale.ROOT) + ")",
                line, "",
                "HASH VERIFICATION",
                "SHA-256 : " + a.hash().sha256(),
                "MD5     : " + a.hash().md5(),
                "", line, "",
                "METADATA"));
        a.metadata().forEach((k, v) -> out.add(String.format("%-16s: %s", k, v)));
        out.addAll(List.of("", line, "",
                "FINDINGS SUMMARY",
                "Critical : " + a.counts().critical(),
                "Warning  : " + a.counts().warning(),
                "Info     : " + a.counts().info(),
                "Clean    : " + a.counts().ok(),
                "", line, "",
                "DETAILED FINDINGS"));
        int i = 1;
        for (var f : a.findings()) {
            out.add("[" + i++ + "] [" + f.severity().toUpperCase(Locale.ROOT) + "] " + f.title());
            out.add("    " + f.desc());
        }
        out.addAll(List.of("", line, "", "SUMMARY", a.aiSummary(), "", line, "", "RECOMMENDATIONS"));
        i = 1;
        for (String r : a.recommendations()) out.add(i++ + ". " + r);
        if (a.notes() != null) out.addAll(List.of("", line, "", "INVESTIGATOR NOTES", a.notes()));
        out.addAll(List.of("", line, "",
                "DISCLAIMER",
                "This report was generated by TraceVault as an analysis aid.",
                "Findings should be reviewed by a qualified forensic examiner.",
                "Automated indicators are not conclusive proof.",
                "",
                "Generated: " + java.time.Instant.now()));

        return new ReportResponse(String.join("\n", out), "tracevault-report-" + a.id() + ".txt", "text");
    }
}
